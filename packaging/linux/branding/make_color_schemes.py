"""
packaging/linux/branding/make_color_schemes.py

Halo Dark and Halo Light, the Plasma colour schemes, made from SAINT's own palette (ui/theme.py) so Plasma,
KDE apps, window borders and SAINT use the same colours. Writes
packaging/linux/rootfs/usr/share/color-schemes/Halo{Dark,Light}.colors (committed; tests check they match).

    python packaging/linux/branding/make_color_schemes.py
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "packaging/linux/rootfs/usr/share/color-schemes"
ACCENT = "#feaa34"


def _rgb(hex_color: str) -> str:
    h = hex_color.lstrip("#")
    return ",".join(str(int(h[i:i + 2], 16)) for i in (0, 2, 4))


def scheme(dark: bool) -> str:
    sys.path.insert(0, str(ROOT))
    from ui.theme import _mix, palette_for
    p = palette_for("Dark" if dark else "Light", ACCENT)
    name = "Halo Dark" if dark else "Halo Light"

    def group(bg, alt, fg=p.text):
        return {"BackgroundNormal": bg, "BackgroundAlternate": alt, "DecorationFocus": p.accent,
                "DecorationHover": p.accent_hover, "ForegroundActive": p.accent, "ForegroundInactive": p.muted,
                "ForegroundLink": p.info, "ForegroundNegative": p.danger, "ForegroundNeutral": p.warning,
                "ForegroundNormal": fg, "ForegroundPositive": p.success, "ForegroundVisited": _mix(p.info, p.danger, 0.4)}

    groups = {
        "Colors:Window": group(p.bg, p.sidebar),
        "Colors:View": group(p.surface, p.surface2),
        "Colors:Button": group(p.raised, p.surface2),
        "Colors:Header": group(p.sidebar, p.bg),
        "Colors:Header][Inactive": group(p.bg, p.sidebar),
        "Colors:Tooltip": group(p.raised, p.surface2),
        "Colors:Complementary": group("#0a0b0d", "#121317", "#eceef2"),
        "Colors:Selection": {**group(p.accent, p.accent_hover, p.on_accent), "ForegroundInactive": p.on_accent,
                             "ForegroundActive": p.on_accent},
    }
    lines = ["# Generated by packaging/linux/branding/make_color_schemes.py from ui/theme.py. Don't edit by hand.",
             "[ColorEffects:Disabled]", "Color=" + _rgb(p.faint), "ColorAmount=0", "ColorEffect=0",
             "ContrastAmount=0.65", "ContrastEffect=1", "IntensityAmount=0.1", "IntensityEffect=2", "",
             "[ColorEffects:Inactive]", "ChangeSelectionColor=true", "Color=" + _rgb(p.bg), "ColorAmount=0.025",
             "ColorEffect=2", "ContrastAmount=0.1", "ContrastEffect=2", "Enable=false", "IntensityAmount=0",
             "IntensityEffect=0", ""]
    for g, keys in groups.items():
        lines.append(f"[{g}]")
        lines += [f"{k}={_rgb(v)}" for k, v in sorted(keys.items())]
        lines.append("")
    lines += ["[General]", f"ColorScheme=Halo{'Dark' if dark else 'Light'}", f"Name={name}", "shadeSortColumn=true", "",
              "[KDE]", "contrast=4", "",
              "[WM]", f"activeBackground={_rgb(p.sidebar)}", f"activeBlend={_rgb(p.text)}",
              f"activeForeground={_rgb(p.text)}", f"inactiveBackground={_rgb(p.bg)}",
              f"inactiveBlend={_rgb(p.muted)}", f"inactiveForeground={_rgb(p.muted)}", ""]
    return "\n".join(lines)


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    for dark in (True, False):
        path = OUT / f"Halo{'Dark' if dark else 'Light'}.colors"
        path.write_text(scheme(dark), encoding="utf-8", newline="\n")
        print(path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
